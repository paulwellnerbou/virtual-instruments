"""Running the builder like an app: start the server on demand, open it, and the macOS launcher."""

import shlex
import socket
import subprocess
import sys
import time
import tomllib
import urllib.request
import webbrowser
from pathlib import Path

APP_PORT = 4780  # fixed, so a page installed as a Chrome app keeps working
APP_NAME = "DecentSampler Instrument Builder"
LOG_FILE = Path("~/Library/Logs/vinst.log").expanduser()
LOG_MAX_BYTES = 1_000_000
START_TIMEOUT_S = 30
CHROME_APPS = Path("~/Applications/Chrome Apps.localized").expanduser()


class LaunchError(Exception):
    """A reason the builder couldn't be opened, worded for the user."""


def builder_running(port: int) -> bool:
    try:
        with urllib.request.urlopen(f"http://127.0.0.1:{port}/", timeout=1) as r:
            return APP_NAME in r.read(4096).decode("utf-8", "replace")
    except (OSError, ValueError):
        return False


def port_in_use(port: int) -> bool:
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
        s.settimeout(0.5)
        return s.connect_ex(("127.0.0.1", port)) == 0


def trim_log(path: Path = LOG_FILE, max_bytes: int = LOG_MAX_BYTES) -> None:
    """Keep the log from growing forever: when it's too big, keep only its newer half."""
    try:
        if path.stat().st_size <= max_bytes:
            return
        data = path.read_bytes()[-max_bytes // 2:]
        path.write_bytes(data[data.find(b"\n") + 1:])
    except OSError:
        pass


def chrome_app(name: str = APP_NAME, folder: Path = CHROME_APPS) -> Path | None:
    """The builder installed as a Chrome app ("Install page as app"), if there is one."""
    candidates = sorted(folder.glob(f"{name}*.app")) if folder.is_dir() else []
    return candidates[0] if candidates else None


def start_server(port: int, idle_exit: float) -> None:
    LOG_FILE.parent.mkdir(parents=True, exist_ok=True)
    trim_log()
    with LOG_FILE.open("a") as log:
        # Its own session, so the server outlives the launcher, which quits right away.
        subprocess.Popen([sys.executable, "-m", "vinst.cli", "ui", "--port", str(port), "--no-show",
                          "--idle-exit", str(idle_exit)], stdout=log, stderr=log, start_new_session=True)


def open_builder(port: int = APP_PORT, idle_exit: float = 120) -> None:
    if not builder_running(port):
        if port_in_use(port):
            raise LaunchError(f"Port {port} is used by another program, so the builder can't start. "
                              "Quit that program and try again.")
        start_server(port, idle_exit)
        deadline = time.monotonic() + START_TIMEOUT_S
        while not builder_running(port):
            if time.monotonic() > deadline:
                raise LaunchError(f"The builder didn't start within {START_TIMEOUT_S} s. Details: {LOG_FILE}")
            time.sleep(0.3)
    app = chrome_app() if sys.platform == "darwin" else None
    if app is not None:
        subprocess.run(["open", "-a", str(app)], check=False)
    else:
        webbrowser.open(f"http://127.0.0.1:{port}/")


def project_root() -> Path:
    """This checkout: the launcher must run the code it was installed from."""
    root = Path(__file__).resolve().parents[2]
    try:
        name = tomllib.loads((root / "pyproject.toml").read_text(encoding="utf-8"))["project"]["name"]
    except (OSError, KeyError, tomllib.TOMLDecodeError):
        name = None
    if name != "vinst":
        raise LaunchError(f"{root} isn't a checkout of this project; run install-app from a cloned repository.")
    return root


LAUNCHER = """#!/bin/sh
# Generated by `vinst install-app`: starts the builder from this checkout and opens it.
# Launch Services can start a script-only app under Rosetta; the universal Python it runs
# would then be x86_64 and fail to load the venv's arm64-only packages.
if [ "$(/usr/sbin/sysctl -n sysctl.proc_translated 2>/dev/null)" = 1 ]; then
  exec /usr/bin/arch -arm64 /bin/sh "$0" "$@"
fi
REPO={repo}
UV={uv}
LOG={log}
fail() {{
  /usr/bin/osascript -e 'on run argv' -e 'display alert (item 1 of argv) message (item 2 of argv) as critical' \\
    -e 'end run' {name} "$1" >/dev/null 2>&1
  exit 1
}}
cd "$REPO" 2>/dev/null || fail "The builder's folder is missing: $REPO. Run 'uv run vinst install-app' from its new location."
[ -x "$UV" ] || fail "uv wasn't found at $UV. Run 'uv run vinst install-app' again."
out=$("$UV" run --quiet vinst open 2>&1)
status=$?
[ -n "$out" ] && printf '%s\\n' "$out" >> "$LOG"
[ "$status" -eq 0 ] || fail "$(printf '%s' "$out" | tail -n 3)"
"""

INFO_PLIST = """<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>{name}</string>
  <key>CFBundleDisplayName</key><string>{name}</string>
  <key>CFBundleIdentifier</key><string>io.github.vinst.instrument-builder</string>
  <key>CFBundleExecutable</key><string>launcher</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleShortVersionString</key><string>1.0</string>
  <!-- Only starts the server and opens the browser, so it never needs a Dock icon. -->
  <key>LSUIElement</key><true/>
</dict>
</plist>
"""


def write_launcher(bundle: Path, repo: Path, uv: Path) -> None:
    macos = bundle / "Contents" / "MacOS"
    macos.mkdir(parents=True, exist_ok=True)
    (bundle / "Contents" / "Info.plist").write_text(INFO_PLIST.format(name=APP_NAME), encoding="utf-8")
    script = macos / "launcher"
    script.write_text(LAUNCHER.format(repo=shlex.quote(str(repo)), uv=shlex.quote(str(uv)),
                                      log=shlex.quote(str(LOG_FILE)), name=shlex.quote(APP_NAME)),
                      encoding="utf-8")
    script.chmod(0o755)
